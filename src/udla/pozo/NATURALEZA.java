package udla.pozo;

public class NATURALEZA {
    private String pais;
    private String region;
    private String alturanm;

    public String getPais() {
        return pais;
    }

    public void setPais(String pais) {
        this.pais = pais;
    }

    public String getRegion() {
        return region;
    }

    public void setRegion(String region) {
        this.region = region;
    }

    public String getAlturanm() {
        return alturanm;
    }

    public void setAlturanm(String alturanm) {
        this.alturanm = alturanm;
    }
}
